#!/usr/bin/env python3
"""hs-rops — the launcher for the `rops` remote-execution router shipped at
`harness/scripts/rops/`, reached from an install through the `hs-rops` binary generated by
`harness/scripts/launchers.py`, same as `hs-cli`/`hs-run`/`hs-code`. Everything —
`--version`, `--list`, `--help`, routing, the envelope — is `rops.rops.HsRopsCli`, the family
core with rops's two extra sources; rops's own 0/1/3/124/125/126 exit codes
(ropslib/exec.py) pass through untouched."""
from __future__ import annotations

import sys
from pathlib import Path

_SCRIPTS = Path(__file__).resolve().parent
_ROOT = _SCRIPTS.parents[1]  # harness/scripts -> harness -> repo root (mirrors hs_code.py)
if str(_SCRIPTS) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS))



def _load_router():
    """The moved `rops` package's own router module, `rops.rops` -- the directory
    `harness/scripts/rops` carries no `__init__.py`, so with `_SCRIPTS`
    (harness/scripts) on `sys.path` Python treats it as an implicit namespace
    package (PEP 420) and this dotted import resolves straight to
    `harness/scripts/rops/rops.py`, a real edge the reachability walker can see.
    Never pre-insert that directory itself onto `sys.path` here: that would let a
    bare `import rops` resolve `rops.py` as a PLAIN module instead of the namespace
    package, and `rops.rops` then fails with "'rops' is not a package". Unlike at
    the old, pre-harness location, the router's own internal imports now spell the
    full dotted name (`from rops.ropslib import ...`, `import rops.verbs as
    verbs_pkg`) -- the move DROPPED the router's own `sys.path.insert(HERE)`, so a
    repo-local verb's documented `from ropslib import ...` (`extending.md`) no
    longer resolves on its own; `HsRopsCli.load_custom_file` aliases `ropslib`/`verbs`
    back onto `sys.modules` before loading a repo verb so that old import shape keeps
    working without a second module copy."""
    import rops.rops as router  # noqa
    return router


def main(argv=None) -> int:
    return _load_router().main(argv)


if __name__ == "__main__":
    sys.exit(main())
