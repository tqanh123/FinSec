"""hs-code scaffold codeowners -- CODEOWNERS generated from the descriptor,
plus a `--check` freshness gate.

Port of ob-tools' `devkit.analysis.codeowners` (pinned commit `60075cb89c`),
near-verbatim: the kernel descriptor has no ownership concept, so this reads
the opaque `domains:` passthrough exactly as upstream does. The shape
accepted is `domains.<plugin>.owners`:

    owners:
      default: ["@team-core"]        # optional fallback
      <root-id>: ["@team-x"]         # keyed by ROOT id (descriptor.roots)

This is a DIFFERENT field from this harness's own top-level `descriptor.
owners` (`codegraph.check.owners`'s `channels`/`ledger`/`stay` block, which
answers "which code CHANNEL owns a module" for `hs-code check owners`) --
the two never collide because one lives at `descriptor.owners` and the other
inside `descriptor.domains[<plugin>]["owners"]`.

A root with no owner and no default gets `@TODO-OWNER` -- never dropped, so
an unowned path stays visible rather than silently missing a row.

WHAT IT CANNOT SEE
    * Real team membership: a wrong declaration is faithfully reproduced.
    * Whether a pattern matches a file -- the forge matches CODEOWNERS, not
      this tool. Patterns come from declared root paths.
    * The forge's last-match-wins ordering subtleties; this emits in
      declaration order and does not validate a hand-edited order.

Exit: 0 rendered (or --check matches) · 1 --check finds the file stale or
missing · 2 no codemap.yaml, no declared roots, or two domains claim the same
root's owners.
"""
from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import hs_family

from codegraph._core.descriptor.model import DescriptorError, require_roots

from ._layout import load_descriptor
from .errors import ScaffoldError
from hs_family.cli import Command

HEADER = (
    "# CODEOWNERS -- GENERATED by `hs-code scaffold codeowners`. Do not edit by hand.\n"
    "# Regenerate after changing root ownership; `hs-code scaffold codeowners --check`\n"
    "# is red when this file and codemap.yaml disagree.\n"
)

TODO_OWNER = "@TODO-OWNER"


class CodeownersError(ScaffoldError):
    """Honest cannot-run (maps to exit 2)."""


@dataclass(frozen=True)
class Rule:
    pattern: str
    owners: "tuple[str, ...]"

    def line(self) -> str:
        return "%s %s" % (self.pattern, " ".join(self.owners))

    @property
    def unowned(self) -> bool:
        return self.owners == (TODO_OWNER,)


def owner_declarations(descriptor: Any) -> "tuple[dict[str, list[str]], list[str]]":
    """-> (root_id -> owners, default owners).

    Merges the `owners:` block from EVERY domain namespace; a collision on
    the same root id (two domains both naming it) is an error, never a
    last-one-wins silently picked by dict order."""
    by_root: "dict[str, list[str]]" = {}
    default: "list[str]" = []
    for plugin, block in sorted((descriptor.domains or {}).items()):
        if not isinstance(block, dict):
            continue
        owners = block.get("owners")
        if not isinstance(owners, dict):
            continue
        for key, value in owners.items():
            seq = [str(v) for v in value] if isinstance(value, (list, tuple)) else [str(value)]
            if key == "default":
                default = seq
                continue
            if key in by_root:
                raise CodeownersError(
                    "root %r has owners declared by more than one domain block "
                    "(collision at %r) -- an owner is one answer, not two" % (key, plugin))
            by_root[key] = seq
    return by_root, default


def build_rules(descriptor: Any) -> "list[Rule]":
    """One rule per declared root, in declaration order."""
    try:
        require_roots(descriptor, why="codeowners needs one rule per root")
    except DescriptorError as e:
        raise CodeownersError(str(e)) from e
    by_root, default = owner_declarations(descriptor)
    rules: "list[Rule]" = []
    seen: "set[str]" = set()
    for root in descriptor.roots:
        pattern = "/%s/" % root.path.strip("/")
        if pattern in seen:
            continue
        seen.add(pattern)
        owners = tuple(by_root.get(root.id) or default) or (TODO_OWNER,)
        rules.append(Rule(pattern, owners))
    return rules


def render(descriptor: Any) -> str:
    lines = [HEADER.rstrip("\n"), ""]
    for r in build_rules(descriptor):
        lines.append(r.line())
    lines.append("")
    return "\n".join(lines)


def body(text: str) -> str:
    """The lines `--check` compares: non-comment, non-blank, stripped -- a
    reworded header must never read as a stale ownership change."""
    return "\n".join(ln.strip() for ln in text.splitlines()
                     if ln.strip() and not ln.lstrip().startswith("#"))


def _diff(want: str, have: str) -> "list[str]":
    want_l, have_l = want.splitlines(), have.splitlines()
    out = ["+ %s" % ln for ln in want_l if ln not in have_l]
    out += ["- %s" % ln for ln in have_l if ln not in want_l]
    return out[:20]


def _codeowners_args(ap: argparse.ArgumentParser) -> None:
    ap.add_argument("-o", "--out", default=None, metavar="FILE",
                    help="write CODEOWNERS here (default: stdout)")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the file on disk is stale (requires -o)")


def _codeowners(args: argparse.Namespace) -> int:
    root, opts = args.ctx.root, args.opts
    repo = Path(root).resolve()
    as_json = bool(getattr(opts, "json", False))

    try:
        descriptor = load_descriptor(repo)
        text = render(descriptor)
    except ScaffoldError as e:
        raise hs_family.UsageError(str(e)) from e

    dest = Path(args.out).resolve() if args.out else None

    if args.check:
        if dest is None:
            raise hs_family.UsageError("scaffold codeowners --check: needs -o FILE (which file to compare)")
        missing_data: "dict[str, Any]" = {"stale": True, "missing": True, "path": str(dest)}
        if not dest.is_file():
            if as_json:
                print(json.dumps(missing_data, sort_keys=True, ensure_ascii=False))
            else:
                print("scaffold codeowners --check: no CODEOWNERS at %s -- nothing to compare" % dest)
            return 1
        want, have = body(text), body(dest.read_text(encoding="utf-8"))
        stale = want != have
        data: "dict[str, Any]" = {"stale": stale, "missing": False, "path": str(dest)}
        if stale:
            data["diff"] = _diff(want, have)
        if as_json:
            print(json.dumps(data, sort_keys=True, ensure_ascii=False))
        else:
            if stale:
                print("scaffold codeowners --check: %s is STALE" % dest)
                for ln in data["diff"]:
                    print("  %s" % ln)
                print("  regenerate: hs-code scaffold codeowners --repo %s -o %s" % (repo, dest))
            else:
                print("scaffold codeowners --check: %s matches codemap.yaml" % dest)
        return 1 if stale else 0

    rules = build_rules(descriptor)
    todo = [r.pattern for r in rules if r.unowned]
    if dest is None:
        data = {"out": None, "rules": len(rules), "unowned": todo}
        if as_json:
            print(json.dumps(data, sort_keys=True, ensure_ascii=False))
        else:
            print(text, end="")
        return 0
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8")
    data = {"out": str(dest), "rules": len(rules), "unowned": todo}
    if as_json:
        print(json.dumps(data, sort_keys=True, ensure_ascii=False))
    else:
        print("scaffold codeowners: wrote %d rule(s) to %s" % (len(rules), dest))
        if todo:
            print("  %d path(s) have NO declared owner (%s):" % (len(todo), TODO_OWNER))
            for p in todo:
                print("    %s" % p)
    return 0


CODEOWNERS_VERB = Command(add_args=_codeowners_args, run=_codeowners)
