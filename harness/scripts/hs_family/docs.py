"""One family CLI's command reference, generated from its registry — on request only.

`hs-cli docs <cli>` is the one caller. No hook and no CI step runs it: a reference
regenerated behind the reader's back is a file that changes in the tree without anyone
having asked, and one never regenerated says so itself (below).

The page names the registry it was read from by ONE hash: sha256 over every file the
command table was built from (its path relative to the install root, then its bytes,
in path order). The same registry gives the same hash and the same page; a change to any
of those files — a row, a help line, a comment — gives another hash. A command's flags
live in its module, not in the registry: they are on the page, not in the hash.

WHAT IT CANNOT SEE
    * A command that is not a row of the table (a script nobody registered): the page is
      the table, nothing else.
"""
from __future__ import annotations

import hashlib
import importlib
import os
from pathlib import Path
from typing import Any, Optional

from .registry import FAMILY

#: the class each family launcher dispatches through, as (module, class)
FAMILY_CLASS = {"hs-run": ("hs_run", "HsRunCli"), "hs-code": ("hs_code", "HsCodeCli"),
                "hs-cli": ("hs_cli", "HsCli"), "hs-rops": ("rops.rops", "HsRopsCli"),
                "hs-secrets": ("secret_store.router", "HsSecretsCli"),
                "hs-usage": ("hs_usage", "HsUsage")}
assert set(FAMILY_CLASS) == set(FAMILY), "every family CLI needs its class here"


def family_cli(name: str, install_root: Optional[Path] = None) -> Any:
    """An instance of the family CLI `name`, reading the registry under `install_root`."""
    mod, cls = FAMILY_CLASS[name]
    return getattr(importlib.import_module(mod), cls)(install_root=install_root)


def source_files(table: Any) -> "list[Path]":
    """Every file a row of `table` came from (a moved row names all of its registry's)."""
    out: set = set()
    for row in table.rows:
        for where in str(row.origin.where).split(", "):
            if where and Path(where).is_file():
                out.add(Path(where).resolve())
    return sorted(out)


def _label(path: Path, root: Path) -> str:
    try:
        return path.relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.as_posix()


def registry_sha256(table: Any, root: Path) -> str:
    h = hashlib.sha256()
    for path in sorted(source_files(table), key=lambda p: _label(p, root)):
        h.update(_label(path, root).encode("utf-8") + b"\0")
        h.update(path.read_bytes() + b"\0")
    return h.hexdigest()


def reference(cli: Any) -> "tuple[str, str, int]":
    """(markdown, registry sha256, live command count) for the CLI instance `cli`."""
    table = cli.table({})
    digest = registry_sha256(table, cli.install_root)
    live = sorted(table.live, key=lambda r: r.path)
    lines = ["# `%s` command reference" % cli.prog, "",
             "Generated by `hs-cli docs %s` from the registry with sha256 `%s` "
             "(%d commands). Nothing regenerates it for you: after a registry change, run "
             "that command again." % (cli.prog, digest, len(live)), ""]
    if cli.description:
        lines += [cli.description, ""]
    lines += ["```text", *cli.footer, "```", ""]
    for row in live:
        cmd = row.load()
        lines += ["## `%s %s`" % (cli.prog, " ".join(row.path)), "", row.help or "(no help)", ""]
        if getattr(cmd, "passthrough", False):
            lines += ["Passthrough: every argument goes to the wrapped tool, whose own help "
                      "lists its flags.", ""]
        else:
            lines += ["```text", cli.command_parser(row, cmd).format_help().rstrip(), "```", ""]
    moved = sorted(table.moved.items())
    if moved:
        lines += ["## Moved", ""]
        lines += ["- `%s %s` → `%s`" % (cli.prog, " ".join(p), t) for p, t in moved]
        lines.append("")
    return "\n".join(lines), digest, len(live)


def write(text: str, out: Path) -> Path:
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_name(out.name + ".tmp.%d" % os.getpid())
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, out)
    return out


__all__ = ["FAMILY_CLASS", "family_cli", "reference", "registry_sha256", "source_files", "write"]
