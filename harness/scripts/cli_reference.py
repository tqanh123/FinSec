#!/usr/bin/env python3
"""cli_reference.py — generate docs/harness/cli-reference.md from the live registries.

One section per family CLI, one row per live verb (moved rows excluded), carrying
the registry's own one-line help. The generated block sits between two fences;
everything outside them is human-owned prose the generator never touches, so the
drift gate (harness/tests/test_cli_reference_doc_matches_registry.py) compares
only the fenced block and stays narrow.

Usage:
  cli_reference.py --write   rewrite the fenced block inside the doc (creating
                             the doc with a short header when absent)
  cli_reference.py --check   exit 0 when the committed block matches the
                             registry render, exit 1 naming the first drift

Reads the SAME loaders the CLIs themselves answer --help from (hs_family.cli
RegistrySource / hs_run.load_registry), never a hand-copied table.
"""

import argparse
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
if str(_HERE) not in sys.path:
    sys.path.insert(0, str(_HERE))

BEGIN = "<!-- BEGIN cli-reference (generated by harness/scripts/cli_reference.py --write) -->"
END = "<!-- END cli-reference -->"

_DOC = _HERE.parent.parent / "docs" / "harness" / "cli-reference.md"

_HEADER = """---
id: harness.cli-reference
type: guide
status: stable
version: 6.3.0
owner: maintainer
---
# CLI reference — every family verb

Generated from the live registries (`harness/data/*-registry*.yaml` + loaders in
`harness/scripts/hs_family/`); regenerate with
`python3 harness/scripts/cli_reference.py --write`. One row per live verb with
the same one-line help the parser itself prints. Prose outside the generated
fences is hand-written and survives regeneration.
"""


def _rows():
    """[(cli, path-tuple, help)] from the live registries, in a fixed CLI order."""
    import hs_family.registry as hs_registry
    from hs_family.cli import RegistrySource

    out = []
    for cli, depth in (("hs-run", 2), ("hs-code", 2), ("hs-cli", 1),
                       ("hs-rops", 1), ("hs-secrets", 1), ("hs-usage", 1)):
        rows = [r for r in RegistrySource(hs_registry.family_env(cli), _REPO_ROOT, depth=depth).rows()
                if r.moved_to is None]
        for r in sorted(rows, key=lambda r: r.path):
            out.append((cli, r.path, r.help or ""))
    return out


_REPO_ROOT = _HERE.parent.parent


def render_block():
    """The fenced markdown block for every live verb."""
    lines = [BEGIN, ""]
    by_cli = {}
    for cli, path, help_text in _rows():
        by_cli.setdefault(cli, []).append((path, help_text))
    for cli in ("hs-run", "hs-code", "hs-cli", "hs-rops", "hs-secrets", "hs-usage"):
        rows = by_cli.get(cli, [])
        domains = len({p[0] for p, _ in rows}) if cli in ("hs-run", "hs-code") else None
        if domains is not None:
            lines.append("## %s — %d domains · %d verbs" % (cli, domains, len(rows)))
        else:
            lines.append("## %s — %d verbs" % (cli, len(rows)))
        lines.append("")
        lines.append("| Verb | Help |")
        lines.append("|---|---|")
        for path, help_text in rows:
            verb = " ".join(path)
            lines.append("| `%s %s` | %s |" % (cli, verb, (help_text or "").replace("|", "\\|")))
        lines.append("")
    lines.append(END)
    return "\n".join(lines) + "\n"


def fenced_block_of(text):
    """The exact content between the fences (fences included), or ''."""
    try:
        i = text.index(BEGIN)
        j = text.index(END) + len(END)
    except ValueError:
        return ""
    return text[i:j] + "\n"


def _write():
    body = _DOC.read_text(encoding="utf-8") if _DOC.is_file() else _HEADER
    block = render_block()
    old = fenced_block_of(body)
    if old:
        new_body = body.replace(old.rstrip("\n"), block.rstrip("\n"), 1)
    else:
        new_body = body.rstrip("\n") + "\n\n" + block
    _DOC.parent.mkdir(parents=True, exist_ok=True)
    _DOC.write_text(new_body, encoding="utf-8")
    print("wrote %s (%d verbs)" % (_DOC, sum(1 for c, p, h in _rows())))


def _check():
    body = _DOC.read_text(encoding="utf-8") if _DOC.is_file() else ""
    want, have = render_block(), fenced_block_of(body)
    if want == have:
        print("cli-reference: in sync (%d verbs)" % sum(1 for c, p, h in _rows()))
        return 0
    wl, hl = want.splitlines(), have.splitlines()
    for i in range(max(len(wl), len(hl))):
        w = wl[i] if i < len(wl) else "<missing>"
        h = hl[i] if i < len(hl) else "<missing>"
        if w != h:
            print("cli-reference DRIFT at fence line %d:\n  registry: %s\n  doc:      %s"
                  % (i + 1, w, h))
            break
    print("Regenerate: python3 harness/scripts/cli_reference.py --write")
    return 1


def main(argv=None):
    ap = argparse.ArgumentParser(prog="cli_reference.py", description=__doc__.split("\n", 1)[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true", help="rewrite the fenced block in the doc")
    g.add_argument("--check", action="store_true", help="exit 1 on drift, naming the first one")
    args = ap.parse_args(argv)
    if args.write:
        _write()
        return 0
    return _check()


if __name__ == "__main__":
    sys.exit(main())
